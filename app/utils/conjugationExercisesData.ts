// Types pour les exercices de conjugaison
export interface ConjugationExercise {
  id: string;
  infinitive: string;
  infinitiveFrench: string;
  person: 'I-m' | 'I-f' | 'you-m' | 'you-f' | 'he' | 'she' | 'we-m' | 'we-f' | 'you-pl-m' | 'you-pl-f' | 'they-m' | 'they-f';
  personHebrew: string;
  tense: 'present' | 'past' | 'future';
  type: 'typing' | 'multiple-choice';
  question: string;
  correctAnswer: string;
  options?: string[];
}

export interface ConjugationExerciseSet {
  id: string;
  title: string;
  exercises: ConjugationExercise[];
}

export interface ExerciseMetadata {
  id: string;
  setNumber: number;
  tense: 'present' | 'past' | 'future';
  title: string;
  description: string;
}

export interface BinyanExerciseMetadata {
  id: string;
  binyan: 'qal' | 'nifal' | 'piel' | 'pual' | 'hifil' | 'hofal' | 'hitpael';
  title: string;
  description: string;
}

export interface GizraExerciseMetadata {
  id: string;
  gizra: 'regular' | 'guttural' | 'weak-alef' | 'weak-yod' | 'weak-vav' | 'weak-nun' | 'doubled';
  title: string;
  description: string;
}

